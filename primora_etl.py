# -*- coding: utf-8 -*-
import pandas as pd
import requests
import time
import re
import unicodedata

# =============================================================================
# 1. CARREGAMENTO DOS DADOS
# =============================================================================
arquivo = '02-clientes_distribuidora_vetor.csv'
df = pd.read_csv(arquivo, sep=';')

# =============================================================================
# 2. FUNÇÕES AUXILIARES DE TRATAMENTO
# =============================================================================
def formatar_telefone(tel):
    # Converte para string e remove tudo o que não for número
    tel_limpo = ''.join(filter(str.isdigit, str(tel)))

    # Se a linha original for nula ou ficar vazia, retorna vazio
    if pd.isna(tel) or not tel_limpo:
        return None

    tam = len(tel_limpo)

    # Cenário 1: Se tem código do país (55 no início e tamanho maior que 11)
    if tel_limpo.startswith('55') and tam > 11:
        tel_limpo = tel_limpo[2:]  # Remove o '55'
        tam = len(tel_limpo)       # Atualiza o tamanho para reavaliar abaixo

    # Cenário 2: Telefone Fixo (10 dígitos: DD + 8 números) -> (XX) XXXX-XXXX
    if tam == 10:
        return f"({tel_limpo[:2]}) {tel_limpo[2:6]}-{tel_limpo[6:]}"

    # Cenário 3: Celular (11 dígitos: DD + 9 números) -> (XX) XXXXX-XXXX
    elif tam == 11:
        return f"({tel_limpo[:2]}) {tel_limpo[2:7]}-{tel_limpo[7:]}"

    # Cenário 4: Se o número não se encaixar em nenhuma regra (inválido ou incompleto)
    return tel_limpo


def limpar_e_validar_email_v2(email):
    if pd.isna(email) or not str(email).strip():
        return None

    # 1. Padroniza para minúsculo e remove espaços nas pontas
    email = str(email).lower().strip()

    # 2. Remove pontuações em excesso (Ex: ".." vira ".")
    email = re.sub(r'\.{2,}', '.', email)

    # 3. Corrige arrobas duplicadas juntas (Ex: "@@" ou "@@@" vira "@")
    email = re.sub(r'@{2,}', '@', email)

    # 4. Validação do @: se ainda restarem múltiplos arrobas separados, é inválido
    if '@' not in email or email.count('@') != 1:
        return "INVÁLIDO: Arrobas incorrigíveis"

    usuario, dominio = email.split('@', 1)

    if not usuario or not dominio:
        return "INVÁLIDO: Estrutura quebrada"

    # 5. Corrige finais de domínio comuns
    dominio = re.sub(r'\.con$', '.com', dominio)
    dominio = re.sub(r'\.brr$', '.br', dominio)
    dominio = re.sub(r'\.com\.brr$', '.com.br', dominio)

    # 6. Remove acentos e cedilhas do domínio (Normalização Unicode)
    dominio_sem_acento = unicodedata.normalize('NFKD', dominio)
    dominio_limpo = ''.join([c for c in dominio_sem_acento if not unicodedata.combining(c)])
    dominio_limpo = dominio_limpo.replace('ç', 'c') # Garante a troca do ç se necessário

    return f"{usuario}@{dominio_limpo}"

# =============================================================================
# 3. PIPELINE DE TRATAMENTO DE COLUNAS
# =============================================================================

# --- TRATAMENTO DE CNPJ ---
# Remove qualquer caractere que NÃO seja número
cnpj_limpo = df['cnpj'].str.replace(r'\D', '', regex=True)
# Garante que todos tenham exatamente 14 dígitos (coloca zeros à esquerda)
cnpj_padrao = cnpj_limpo.str.zfill(14)
# Aplica a formatação oficial do CNPJ
df['cnpj_formatado'] = (
    cnpj_padrao.str[:2] + '.' +
    cnpj_padrao.str[2:5] + '.' +
    cnpj_padrao.str[5:8] + '/' +
    cnpj_padrao.str[8:12] + '-' +
    cnpj_padrao.str[12:]
)

# --- TRATAMENTO DE TELEFONE ---
df['telefone_formatado'] = df['telefone'].apply(formatar_telefone)

# --- TRATAMENTO DE DATA DE CADASTRO ---
# Converte para o tipo datetime respeitando o dia primeiro
df['data_padronizada'] = pd.to_datetime(
    df['data_cadastro'],
    format='mixed',
    dayfirst=True,   # Força o dia antes do mês em casos ambíguos
    errors='coerce'  # Evita erros se houver algum texto totalmente inválido
)
# Transforma em texto no formato brasileiro padrão (DD/MM/AAAA)
df['data_padronizada'] = df['data_padronizada'].dt.strftime('%d/%m/%Y')

# --- TRATAMENTO DE E-MAIL ---
df['email_tratado'] = df['email'].apply(limpar_e_validar_email_v2)

# --- TRATAMENTO DE CEP E BAIRRO (INTEGRAÇÃO VIA CEP) ---
# Limpeza do CEP (apenas números)
df['cep_limpo'] = df['cep'].astype(str).str.replace(r'\D', '', regex=True)
df.loc[df['cep_limpo'].isin(['00000000', '', 'nan']), 'cep_limpo'] = None

# Filtra apenas os CEPs ÚNICOS válidos para economizar requisições
ceps_unicos = df['cep_limpo'].dropna().unique()
cache_bairros = {}

print(f"Iniciando a consulta de {len(ceps_unicos)} CEPs únicos na API...")

for cep in ceps_unicos:
    try:
        url = f"https://viacep.com.br/ws/{cep}/json/"
        response = requests.get(url, timeout=5)

        if response.status_code == 200:
            dados = response.json()
            if "erro" not in dados:
                cache_bairros[cep] = dados.get('bairro', '')
            else:
                cache_bairros[cep] = "CEP Não Encontrado"
        else:
            cache_bairros[cep] = "Erro na API"
    except Exception:
        cache_bairros[cep] = "Erro de Conexão"

    # Pausa de 0.1 segundos entre requisições para respeitar o servidor do ViaCEP
    time.sleep(0.1)

# Aplica o mapeamento de volta para o DataFrame
df['bairro_oficial_api'] = df['cep_limpo'].map(cache_bairros)

# Regra de Negócio: Se a API retornou o bairro, usamos ele. Caso contrário, mantém o informado originalmente.
df['bairro_final'] = df['bairro_oficial_api'].fillna(df['bairro_informado'])

# Limpa textos de erro da API para não poluírem a coluna final
erros_api = ["CEP Não Encontrado", "Erro na API", "Erro de Conexão"]
df.loc[df['bairro_final'].isin(erros_api), 'bairro_final'] = df['bairro_informado']

# =============================================================================
# 4. SALVAMENTO DOS DADOS TRATADOS
